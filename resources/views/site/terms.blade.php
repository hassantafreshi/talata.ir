        <h2>۱. سرویس</h2>
        <p>زرلیو (zarlio.ir) نرم‌افزار آنلاین صدور فاکتور فروش، محاسبه قیمت طلا و نگهداری اطلاعات مشتریان برای طلافروشی‌ها است. زرلیو فروشنده کالا نیست و طرف معامله میان فروشگاه و مشتری او نیست.</p>
        <h2>۲. حساب کاربری</h2>
        <p>ورود با شماره موبایل و کد پیامکی است. نگهداری گوشی و کدها بر عهده کاربر است. مالک فروشگاه مسئول کارهایی است که همکارانش با دسترسی داده‌شده انجام می‌دهند.</p>
        <h2>۳. درستی اطلاعات و محاسبه</h2>
        <p>نام، نشانی و اطلاعات فروشگاه و مشتری را کاربر وارد می‌کند و مسئول درستی آن است. نرخ‌ها از سرویس نرخ دریافت یا به‌دست کاربر وارد می‌شود؛ پیش از صدور، مبلغ‌ها را بررسی کنید. فاکتور صادرشده تغییر نمی‌کند و فقط باطل یا جایگزین می‌شود.</p>
        <h2>۴. مالیات و قوانین صنفی</h2>
        <p>رعایت قوانین مالیاتی و صنفی، از جمله ثبت در سامانه‌های رسمی، بر عهده فروشگاه است. زرلیو در این نسخه به سامانه مؤدیان متصل نیست و نرخ مالیات پیش‌فرض باید با مشاور مالیاتی تأیید شود.</p>
        <h2>۵. پلن، پرداخت و پیامک</h2>
        <p>قیمت پلن‌ها و اعتبار پیامک در صفحه پلن‌ها آمده است و مالیات بر ارزش افزوده جدا اضافه می‌شود. هزینه پیامک به ازای هر بخش از اعتبار کم می‌شود. پیامک فقط برای اطلاع‌رسانی فاکتور و یادآوری قسط ارسال می‌شود؛ ارسال تبلیغ ممنوع است.</p>
        <h2>۶. استفاده ممنوع</h2>
        <p>استفاده از نام بانک‌ها و نهادها، ارسال پیامک مزاحم یا فریبنده و هر استفاده خلاف قانون ممنوع است و ممکن است به تعلیق حساب منجر شود.</p>
